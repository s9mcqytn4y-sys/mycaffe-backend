-- Refuses while devices, catalog snapshots or their audit history exist.

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM devices) OR EXISTS (SELECT 1 FROM catalog_versions)
       OR EXISTS (SELECT 1 FROM audit_logs WHERE action IN ('DEVICE_REGISTERED', 'DEVICE_RENAMED', 'DEVICE_REVOKED', 'DEVICE_PIN_VERIFIER_ISSUED')) THEN
        RAISE EXCEPTION 'Device history exists; cannot roll back 000038.';
    END IF;
END $$;

ALTER TABLE audit_logs DROP CONSTRAINT IF EXISTS chk_audit_logs_action;
