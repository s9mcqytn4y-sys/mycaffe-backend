-- Refuses while ingredients, movements, costed lines or their audit history exist.

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM ingredients) OR EXISTS (SELECT 1 FROM order_items WHERE cogs_amount IS NOT NULL)
       OR EXISTS (SELECT 1 FROM products WHERE unit_cost <> 0)
       OR EXISTS (SELECT 1 FROM audit_logs WHERE action IN ('INGREDIENT_CREATED', 'INGREDIENT_UPDATED', 'RECIPE_CHANGED')) THEN
        RAISE EXCEPTION 'Inventory history exists; cannot roll back 000045.';
    END IF;
END $$;

ALTER TABLE audit_logs DROP CONSTRAINT IF EXISTS chk_audit_logs_action;
