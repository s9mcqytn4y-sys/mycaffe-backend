-- Refuses while stock sessions or their audit history exist.

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM stock_sessions)
       OR EXISTS (SELECT 1 FROM audit_logs WHERE action IN ('STOCK_SESSION_SUBMITTED', 'STOCK_SESSION_APPROVED', 'STOCK_SESSION_REJECTED')) THEN
        RAISE EXCEPTION 'Stock sessions exist; cannot roll back 000048.';
    END IF;
END $$;

ALTER TABLE audit_logs DROP CONSTRAINT IF EXISTS chk_audit_logs_action;
