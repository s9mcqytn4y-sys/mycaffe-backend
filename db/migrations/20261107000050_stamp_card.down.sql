-- 20261107000050_stamp_card.down.sql
-- Refuses while stamps, customer-linked orders or their audit history exist.

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM customer_stamps) OR EXISTS (SELECT 1 FROM orders WHERE customer_id IS NOT NULL)
       OR EXISTS (SELECT 1 FROM audit_logs WHERE action IN ('STAMP_PROGRAM_CHANGED', 'STAMP_REWARD_REDEEMED')) THEN
        RAISE EXCEPTION 'Stamp card data exists; cannot roll back 000050.';
    END IF;
END $$;

