-- Refuses while business customers, charged orders or their audit history exist.

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM business_customers) OR EXISTS (SELECT 1 FROM payments WHERE method = 'invoice')
       OR EXISTS (SELECT 1 FROM audit_logs WHERE action IN ('BUSINESS_CUSTOMER_CHANGED', 'INVOICE_CHARGED', 'INVOICE_ISSUED', 'INVOICE_PAYMENT_RECORDED')) THEN
        RAISE EXCEPTION 'Invoice data exists; cannot roll back 000055.';
    END IF;
END $$;

